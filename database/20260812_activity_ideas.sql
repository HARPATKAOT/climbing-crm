-- טיול שעדיין אין לו תאריך, ובכל זאת יש לו רשימה.
--
-- „אני חושב להוציא טיול סנפלינג” הוא הרגע שבו אנשים הכי מתעניינים, והוא בדיוק
-- הרגע שבו לא היה לנו לאן לרשום אותם: רשימת המתעניינים תלויה באירוע קיים
-- ביומן, והבוט מציע רק אירועים עם תאריך שמסומנים לפרסום. מי ששאל נענה „אין
-- אירועים פתוחים”, והעניין נעלם.
--
-- רעיון הוא פעילות עם שם, בלי תאריך, שלא מתפרסמת ולא נפתחת להרשמה — אבל כן
-- אוספת מתעניינים. כשנקבע לה תאריך, כל מי שברשימה מקבל הודעה.

alter table if exists public.activities
  add column if not exists collect_interest boolean default false;

comment on column public.activities.collect_interest is
  'פעילות שאוספת מתעניינים. בלי תאריך היא „רעיון” — לא מתפרסמת ולא נפתחת להרשמה.';

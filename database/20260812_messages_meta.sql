-- מה שהודעה צריכה לזכור מעבר לטקסט ולקובץ נדחס עד היום לתוך media_url. זה
-- עבד לסוג הקובץ ולשם שלו — הם באמת מתארים את הקובץ — ונשבר ברגע שהודעה צריכה
-- לזכור *על מה* היא מגיבה: ריאקציה מצביעה על בועה אחרת, ציטוט-תגובה מצביע על
-- בועה אחרת, ושתיהן נאלצו לרכוב על עמודה שכל תפקידה להצביע על קובץ.
--
-- העמודה nullable ובלי ברירת מחדל, ולכן ה-ALTER הוא שינוי מטא-דאטה בלבד:
-- Postgres לא כותב מחדש אף שורה קיימת בטבלה.
--
-- מה נכנס לכאן: reply_to (ה-wamid שצוטט), reaction_to (ה-wamid שעליו הגיבו),
-- ובעתיד כל שדה שלא מצדיק עמודה משלו. media_url חוזר לתפקידו היחיד — איפה
-- הקובץ. שורות שנכתבו לפני המיגרציה נקראות משני המקומות.
alter table messages add column if not exists meta jsonb;

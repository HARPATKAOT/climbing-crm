-- רמת הקבוצה: מתחילים / מתקדמים.
--
-- עד היום קבוצת נבחרת נראתה לבוט בדיוק כמו חוג רגיל באותה שכבה, ולכן הוא הציע
-- אותה גם למי ששואל בפעם הראשונה. השם („נבחרת בוגרת”) הוא רמז, לא נתון —
-- אז זה שדה אמיתי שנבחר במסך הקבוצה.
--
-- ריק = קבוצה רגילה שמתאימה לכולם, וזו ברירת המחדל של כל הקבוצות הקיימות,
-- כך שהוספת העמודה לא משנה שום תשובה עד שמסמנים קבוצה כמתקדמת.
alter table public.groups
  add column if not exists skill_level text;

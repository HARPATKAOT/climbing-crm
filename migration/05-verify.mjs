#!/usr/bin/env node
/**
 * migration/05-verify.mjs — the cutover gate for the Supabase region move
 * (ap-northeast-2 / Seoul  ->  eu-central-1 / Frankfurt).
 *
 * ─── READ-ONLY GUARANTEE ────────────────────────────────────────────────────
 * This script NEVER writes to either database. There is no INSERT, UPDATE,
 * DELETE, UPSERT, TRUNCATE, DDL, storage upload/remove or Management-API call
 * anywhere in it. Three independent layers enforce that:
 *
 *   1. Every statement it sends is a SELECT / WITH / SHOW, except three fixed
 *      session settings sent once per connection (see ReadOnlyConnection.
 *      connect). Those three are string literals in the source; nothing
 *      builds them and nothing else bypasses the guard.
 *   2. ReadOnlyConnection.query() refuses to send anything whose first keyword
 *      is not SELECT / WITH / SHOW, and refuses statement batching (';').
 *   3. Immediately after connecting, each session is put into
 *      `SET SESSION CHARACTERISTICS AS TRANSACTION READ ONLY` and the setting
 *      is read back, so PostgreSQL itself rejects a write with "cannot execute
 *      INSERT in a read-only transaction" even if layers 1 and 2 were defeated.
 *
 * It also never prints a secret. Connection strings are shown as
 * user@host:port/db with the password stripped.
 * The only file it may write is the optional --json report.
 *
 * ─── WHAT IT COMPARES ───────────────────────────────────────────────────────
 * (numbered as the run prints them)
 *   0. The table inventory parsed out of server/supa.js, against the 27 + 77
 *      this kit was written for. Drift is a WARN; the parsed list always wins.
 *   1. Sanity of the comparison itself: every collector ran, the SOURCE is not
 *      empty (two empty databases match on everything), engine versions agree,
 *      and no table has FORCE ROW LEVEL SECURITY silently zeroing its count.
 *   2. Row count per DIRECT table (the 27 real Postgres tables in supa.js).
 *      A declared table missing from BOTH databases is a FAIL, not a match:
 *      db.js initDb() hydrates every CORE_TABLE and exits the process if one
 *      cannot be read, so Render would crash-loop.
 *   3. Row count per other public table (kv_collections, app_settings and the
 *      legacy tables that a dump carries but the app reads from kv).
 *   4. Row count per kv_collections collection (the 77 operational tables
 *      declared in supa.js today).
 *   5. last_value of every public sequence. lead_status_history.id is
 *      GENERATED BY DEFAULT AS IDENTITY; if the restore leaves its sequence
 *      behind the data, the record_lead_status_change() trigger makes EVERY
 *      parent/student update fail on a duplicate key. A data-only restore is
 *      the classic way to produce exactly that.
 *   6. auth.users / auth.identities / users holding a password hash.
 *      These live in the `auth` schema — a public-schema-only dump loses them
 *      and every staff login fails.
 *   7. Object count and total bytes per storage bucket, plus the public flag.
 *      Bucket objects are NOT carried by a Postgres dump, and 'product-images'
 *      must stay public or every catalog photo 404s.
 *   8. Rows containing the OLD project ref (absolute storage URLs that never
 *      self-heal) — must be 0 on the target after step 04 — AND rows containing
 *      the NEW ref, which must have picked up what the old ref lost. Checking
 *      only "old ref is gone" passes a step-04 bug that blanked the URLs.
 *   9. Presence of every SECURITY DEFINER function, plus the append-only
 *      trigger on kv_collections that seals the signature-evidence journal.
 *      Lost in the restore is a FAIL; absent on both sides means the migration
 *      was never applied to production, which is a WARN.
 *  10. RLS per public table, and whether anon / PUBLIC / authenticated hold
 *      write grants, SELECT grants, or EXECUTE on a SECURITY DEFINER function.
 *
 * Category 10 is judged as a REGRESSION against the source, not as an absolute.
 * A hole that already exists in production today is a WARN (fix it separately —
 * blocking a region move on it only teaches the operator to ignore this gate);
 * a hole the restore OPENED is a FAIL. That distinction is the whole point
 * here: a fresh Supabase project ships ALTER DEFAULT PRIVILEGES granting
 * anon/authenticated on the public schema, so a restore very often re-grants
 * exactly what database/20260814_enforce_api_only_access.sql revoked.
 * Grants are read from pg_class.relacl / pg_proc.proacl with acldefault()
 * applied, so a NULL ACL is correctly reported as "PUBLIC has EXECUTE".
 *
 * ─── WHAT IT DOES *NOT* CHECK ───────────────────────────────────────────────
 * Nothing outside the two databases. In particular it cannot see whether
 * EVIDENCE_SIGNING_SECRET was set on Render to the OLD service_role key, and it
 * cannot see whether the Vercel client was rebuilt against the new anon key.
 * Both are mandatory and both are invisible from here; the run prints them as a
 * reminder on every outcome, PASS or FAIL.
 *
 * ─── USAGE ──────────────────────────────────────────────────────────────────
 *   node migration/05-verify.mjs --target-url "postgresql://postgres.NEWREF:...@aws-1-eu-central-1.pooler.supabase.com:5432/postgres"
 *   node migration/05-verify.mjs                  # target from env / .env.target
 *   node migration/05-verify.mjs --source-only    # pre-migration baseline
 *   node migration/05-verify.mjs --diff-only      # print only rows that differ
 *   node migration/05-verify.mjs --json out.json  # machine-readable report
 *   node migration/05-verify.mjs --help
 *
 * Connection strings resolve in this order (first hit wins):
 *   SOURCE: --source-url, $SOURCE_DATABASE_URL, env-file SOURCE_DATABASE_URL,
 *           $DATABASE_URL, env-file DATABASE_URL
 *   TARGET: --target-url, $TARGET_DATABASE_URL, target-env-file
 *           TARGET_DATABASE_URL or DATABASE_URL, env-file TARGET_DATABASE_URL
 * Use the SESSION-mode pooler (aws-1-<region>.pooler.supabase.com:5432, user
 * postgres.<ref>). The direct db.<ref>.supabase.co host is IPv6-only, and the
 * TRANSACTION-mode pooler on :6543 does not keep `SET` across statements, so
 * the read-only session guard cannot be established there.
 *
 * ─── EXIT CODES ─────────────────────────────────────────────────────────────
 *   0  every category PASSed (WARN does not gate). Cutover may proceed.
 *   1  at least one category FAILed. Do not cut over.
 *   2  the verification could not be run at all (bad config, no connection).
 *
 * Requires Node 20+. Uses only `pg`, already a server/package.json dependency.
 */


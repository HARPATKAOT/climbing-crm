function fmtBytes(value) {
  if (value === null || value === undefined) return '—';
  const units = ['B', 'KB', 'MB', 'GB', 'TB'];
  let n = Number(value);
  let unit = 0;
  while (n >= 1024 && unit < units.length - 1) {
    n /= 1024;
    unit += 1;
  }
  const shown = unit === 0 ? String(Math.round(n)) : n.toFixed(1);
  return `${shown} ${units[unit]}`;
}

/** Column-aligned ASCII table. `align` is a string of 'l'/'r' per column. */
function renderTable(headers, rows, align) {
  if (!rows.length) return;
  const columns = headers.length;
  const visibleLength = (text) => String(text).replace(/\[[0-9;]*m/g, '').length;
  const widths = headers.map((header, index) =>
    Math.max(
      visibleLength(header),
      ...rows.map((row) => visibleLength(row[index] ?? ''))
    )
  );
  const padCell = (text, index) => {
    const raw = String(text ?? '');
    const gap = widths[index] - visibleLength(raw);
    const pad = ' '.repeat(Math.max(0, gap));
    return align[index] === 'r' ? pad + raw : raw + pad;
  };
  const line = (cells) =>
    cells.map((cell, index) => padCell(cell, index)).join('  ').trimEnd();

  console.log(dim(line(headers)));
  console.log(dim(widths.map((width) => '-'.repeat(width)).join('  ')));
  for (const row of rows) console.log(line(row.slice(0, columns)));
}


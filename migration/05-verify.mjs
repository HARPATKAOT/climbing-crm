function parseArgs(argv) {
  const options = {
    sourceUrl: '',
    targetUrl: '',
    envFile: '',
    targetEnvFile: '',
    oldRef: DEFAULT_OLD_PROJECT_REF,
    oldRefExplicit: false,
    newRef: '',
    sourceOnly: false,
    diffOnly: false,
    jsonPath: '',
    statementTimeout: 300000,
    strictSsl: false,
    noSsl: false,
    help: false,
  };
  const takeValue = (index, flag) => {
    const value = argv[index + 1];
    if (value === undefined || value.startsWith('--')) {
      throw new Error(`${flag} needs a value`);
    }
    return value;
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    switch (arg) {
      case '--source-url': options.sourceUrl = takeValue(index, arg); index += 1; break;
      case '--target-url': options.targetUrl = takeValue(index, arg); index += 1; break;
      case '--env-file': options.envFile = takeValue(index, arg); index += 1; break;
      case '--target-env': options.targetEnvFile = takeValue(index, arg); index += 1; break;
      case '--old-ref':
        options.oldRef = takeValue(index, arg);
        options.oldRefExplicit = true;
        index += 1;
        break;
      case '--new-ref': options.newRef = takeValue(index, arg); index += 1; break;
      case '--json': options.jsonPath = takeValue(index, arg); index += 1; break;
      case '--statement-timeout':
        options.statementTimeout = Number(takeValue(index, arg));
        index += 1;
        break;
      case '--source-only': options.sourceOnly = true; break;
      case '--diff-only': options.diffOnly = true; break;
      case '--strict-ssl': options.strictSsl = true; break;
      case '--no-ssl': options.noSsl = true; break;
      case '--help':
      case '-h': options.help = true; break;
      default:
        throw new Error(`Unknown argument: ${arg}`);
    }
  }
  if (!Number.isFinite(options.statementTimeout) || options.statementTimeout < 1000) {
    throw new Error('--statement-timeout must be at least 1000 (ms)');
  }
  // An empty or short ref would turn strpos(row::text, ref) into "matches
  // everything" and silently report the whole database as contaminated.
  for (const [flag, value] of [['--old-ref', options.oldRef], ['--new-ref', options.newRef]]) {
    if (value && !PROJECT_REF_PATTERN.test(value)) {
      throw new Error(`${flag} does not look like a Supabase project ref: "${value}"`);
    }
  }
  if (!options.oldRef) throw new Error('--old-ref must not be empty');
  return options;
}


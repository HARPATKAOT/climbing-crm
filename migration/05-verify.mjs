// ─── The table inventory, read from server/supa.js ──────────────────────────

/**
 * Read DIRECT_TABLES / OPERATIONAL_TABLES out of server/supa.js instead of
 * duplicating them here: a table added to the app but not to this list would
 * otherwise be verified by nobody.
 */
function parseTableList(source, constantName) {
  const start = source.indexOf(`${constantName} = [`);
  if (start === -1) throw new Error(`${constantName} not found in server/supa.js`);
  const open = source.indexOf('[', start);
  const close = source.indexOf('\n];', open);
  if (close === -1) throw new Error(`${constantName} array is not terminated in server/supa.js`);
  const body = source.slice(open + 1, close).replace(/\/\/[^\n]*/g, '');
  const names = [...body.matchAll(/'([A-Za-z0-9_]+)'/g)].map((match) => match[1]);
  const unique = [...new Set(names)];
  if (!unique.length) throw new Error(`${constantName} parsed as empty from server/supa.js`);
  for (const name of unique) {
    if (!VALID_IDENTIFIER.test(name)) {
      throw new Error(`${constantName} contains an unusable identifier: ${name}`);
    }
  }
  return unique;
}

function loadTableInventory() {
  const supaPath = path.join(REPO_ROOT, 'server', 'supa.js');
  const source = fs.readFileSync(supaPath, 'utf8');
  return {
    supaPath,
    direct: parseTableList(source, 'DIRECT_TABLES'),
    operational: parseTableList(source, 'OPERATIONAL_TABLES'),
  };
}


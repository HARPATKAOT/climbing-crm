/**
 * מי שקיבל קישור לטופס ולא מילא אותו.
 *
 * אורטל כתבה, קיבלה את ימי הקבוצות ואת הקישור לטופס ההשתתפות, ולא מילאה. איש
 * לא חזר אליה: תזכורת נקבעת רק אחרי שיבוץ, ומי שנעצר לפני השיבוץ פשוט נשר.
 * כשראינו את זה החלון של 24 השעות כבר נסגר, וגם תשובה כבר לא הייתה אפשרית.
 *
 * הקישור לטופס הוא הרגע היחיד שאפשר לזהות בוודאות — הוא נשלח בכל מסלול אפשרי
 * (הרשמה, חידוש, בקשת צוות), ולכן הזיהוי הוא על ההודעה היוצאת עצמה ולא על
 * הכלי שיצר אותה. תזכורת אחת ללקוח, והיא נופלת מעצמה ברגע שהטופס נחתם.
 */

/** הנתיבים שדרכם נשלח טופס השתתפות — לפי מתאמן או לפי טלפון. */
const FORM_LINK = /\/api\/f(p)?\//;

export function replyOffersForm(text) {
  return FORM_LINK.test(String(text || ''));
}

/**
 * האם עדיין חסר טופס למישהו בכרטיס.
 *
 * כרטיס בלי מתאמנים כלל הוא בדיוק המקרה של אורטל — הטופס הוא שפותח את כרטיס
 * המתאמן, ולכן היעדר מתאמן הוא היעדר טופס.
 */
export function formStillMissing(students = [], eligibilityOf) {
  if (!students.length) return true;
  return students.some((student) => !eligibilityOf(student.id)?.eligible);
}

/** הגוף בלבד; הפתיח מגיע מ-followUpMessage, כמו בשאר סוגי המעקב. */
export function formFollowUpLine({ link = '' } = {}) {
  if (!link) return '';
  return [
    'רק בודק מה קורה 🙂',
    'שלחתי לכם טופס השתתפות ואני לא רואה שהוא מולא. בלעדיו אי אפשר לשבץ לקבוצה,',
    'והוא לוקח דקה:',
    link,
    'אם נתקלתם במשהו — כתבו לי ואשמח לעזור.',
  ].join('\n');
}
